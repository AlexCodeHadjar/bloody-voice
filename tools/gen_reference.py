"""Reference files for Claude (and people): where everything is, without searching the code.

Run from the project root:  python tools/gen_reference.py   (tools/check_all.sh runs it every time)
Writes docs/reference/:
  code.md    — every script: class name, what it is (its first ## line), public functions
  data.md    — data files with their ids, locale key families
  assets.md  — art and audio in the game (art/, audio/) by folder, and which prompt files still miss images
decisions.md in the same folder is hand-written (owner decisions, open questions) and is never touched here.
"""
from __future__ import annotations

import csv
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"
CODE_DIRS = ["autoload", "core", "scenes", "ui", "tests"]
HEADER = "<!-- generated by tools/gen_reference.py — do not edit by hand -->\n\n"
FUNC_RE = re.compile(r"^(static )?func ([a-z][a-z0-9_]*)\(", re.M)


def _doc_line(text: str) -> str:
    for line in text.splitlines()[:8]:
        if line.startswith("##"):
            return line.lstrip("# ").strip()
    return ""


def code_md() -> str:
    autoloads = re.findall(r'^(\w+)="\*res://([^"]+)"', (ROOT / "project.godot").read_text(encoding="utf-8"), re.M)
    lines = ["# Code map", "", "Autoloads: " + ", ".join(f"`{n}` ({p})" for n, p in autoloads), ""]
    undocumented: list[str] = []
    for top in CODE_DIRS:
        files = sorted((ROOT / top).rglob("*.gd"))
        if not files:
            continue
        lines += [f"## {top}/", "", "| File | Class | What | Public functions |", "|---|---|---|---|"]
        for f in files:
            text = f.read_text(encoding="utf-8")
            cls = re.search(r"^class_name (\w+)", text, re.M)
            funcs = [m.group(2) for m in FUNC_RE.finditer(text) if not m.group(2).startswith("_")]
            doc = _doc_line(text)
            if not doc:
                undocumented.append(f.relative_to(ROOT).as_posix())
            lines.append(f"| `{f.relative_to(ROOT).as_posix()}` | {cls.group(1) if cls else ''} | {doc} | "
                         f"{', '.join(funcs[:20])}{' …' if len(funcs) > 20 else ''} |")
        lines.append("")
    tools = sorted((ROOT / "tools").glob("*.py")) + sorted((ROOT / "tools").glob("*.sh"))
    lines += ["## tools/", "", "| File | What |", "|---|---|"]
    for f in tools:
        text = f.read_text(encoding="utf-8")
        doc = re.search(r'"""(.+?)(?:\n|""")', text) or re.search(r"^# (.+)$", text, re.M)
        lines.append(f"| `{f.relative_to(ROOT).as_posix()}` | {doc.group(1).strip() if doc else ''} |")
    if undocumented:
        lines += ["", "Scripts without a `##` line at the top (add one): " + ", ".join(f"`{u}`" for u in undocumented)]
    return HEADER + "\n".join(lines) + "\n"


def _ids(value) -> list[str]:
    if isinstance(value, list):
        if value and isinstance(value[0], dict) and "icons" in value[0]:  # data/ui/icons.json: sets of icons
            return [f"{s.get('set')} {len(s.get('icons', []))}" for s in value]
        return [str(x.get("id")) for x in value if isinstance(x, dict) and "id" in x]
    if isinstance(value, dict):
        for key in ("monsters", "cards"):
            if isinstance(value.get(key), list):
                return _ids(value[key])
        return [k for k in value if not k.startswith("_")]
    return []


def data_md() -> str:
    lines = ["# Data map", "", "| File | Entries | Ids (or top-level keys) |", "|---|---|---|"]
    for f in sorted((ROOT / "data").rglob("*.json")):
        ids = _ids(json.loads(f.read_text(encoding="utf-8")))
        shown = ", ".join(ids[:18]) + (" …" if len(ids) > 18 else "")
        lines.append(f"| `{f.relative_to(ROOT).as_posix()}` | {len(ids)} | {shown} |")
    table = ROOT / "locale" / "strings.csv"
    if table.exists():
        with table.open(encoding="utf-8", newline="") as fh:
            keys = [r[0] for r in csv.reader(fh)][1:]
        fam = Counter(k.split(".")[0] for k in keys)
        lines += ["", f"## Locale `locale/strings.csv` — {len(keys)} keys", "",
                  " · ".join(f"`{k}.*` {n}" for k, n in sorted(fam.items()))]
    return HEADER + "\n".join(lines) + "\n"


def assets_md() -> str:
    lines = ["# Assets in the game", ""]
    for top in ("art", "audio"):
        base = ROOT / top
        if not base.exists():
            continue
        per_dir: dict[str, list[str]] = defaultdict(list)
        for f in base.rglob("*"):
            if f.is_file() and f.suffix.lower() in (".webp", ".png", ".ogg", ".wav", ".mp3"):
                per_dir[f.parent.relative_to(ROOT).as_posix()].append(f.stem)
        lines += [f"## {top}/", "", "| Folder | Files | Prefixes |", "|---|---|---|"]
        for d in sorted(per_dir):
            pre = Counter(s.split("__")[0] for s in per_dir[d])
            lines.append(f"| `{d}` | {len(per_dir[d])} | " + ", ".join(f"{p} {n}" for p, n in sorted(pre.items())) + " |")
        lines.append("")
    have = {f.stem for f in (ROOT / "art").rglob("*.webp")} | {f.stem for f in (ROOT / "assets").rglob("*.*")}
    lines += ["## Prompt files: images not delivered yet", "", "| Prompt file | Named | Missing |", "|---|---|---|"]
    name_re = re.compile(r"`(?:[\w/]+/)?([A-Z][A-Z0-9_]*__[a-z0-9_]+(?:__[a-z0-9_]+)*)\.png`")
    for f in sorted((ROOT / "docs" / "art-prompts").glob("*.md")):
        names = {n for n in name_re.findall(f.read_text(encoding="utf-8")) if not n.endswith(("__grid", "__frame", "__sheet"))}
        missing = sorted(n for n in names if n not in have)
        if names:
            lines.append(f"| `{f.name}` | {len(names)} | {len(missing)}{': ' + ', '.join(missing[:12]) if missing else ''}"
                         f"{' …' if len(missing) > 12 else ''} |")
    return HEADER + "\n".join(lines) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in (("code.md", code_md()), ("data.md", data_md()), ("assets.md", assets_md())):
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print("reference ->", OUT)


if __name__ == "__main__":
    main()
